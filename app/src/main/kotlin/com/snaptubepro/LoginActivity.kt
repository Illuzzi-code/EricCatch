package com.ericcatch

import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Bundle
import android.util.Log
import android.webkit.CookieManager
import android.widget.Toast
import androidx.appcompat.app.AlertDialog
import androidx.appcompat.app.AppCompatActivity
import androidx.browser.customtabs.CustomTabsIntent
import com.ericcatch.databinding.ActivityLoginBinding
import java.io.File

/**
 * Flujo de login:
 * 1. Abre YouTube en Chrome Custom Tab (Google no lo bloquea)
 * 2. El usuario inicia sesión normalmente en Chrome
 * 3. Vuelve a la app y toca "Ya inicié sesión"
 * 4. Leemos las cookies del CookieManager compartido entre WebView y Chrome
 * 5. Guardamos el archivo cookies.txt para yt-dlp
 */
class LoginActivity : AppCompatActivity() {

    private lateinit var binding: ActivityLoginBinding

    companion object {
        const val COOKIES_FILE = "youtube_cookies.txt"
        private const val TAG = "LoginActivity"

        fun getCookiesFile(context: Context): File? {
            val f = File(context.filesDir, COOKIES_FILE)
            return if (f.exists() && f.length() > 100) f else null
        }

        fun isLoggedIn(context: Context) = getCookiesFile(context) != null

        fun clearSession(context: Context) {
            File(context.filesDir, COOKIES_FILE).delete()
        }
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        binding = ActivityLoginBinding.inflate(layoutInflater)
        setContentView(binding.root)
        setSupportActionBar(binding.loginToolbar)
        supportActionBar?.setDisplayHomeAsUpEnabled(true)

        showInstructions()
    }

    override fun onSupportNavigateUp(): Boolean { finish(); return true }

    private fun showInstructions() {
        AlertDialog.Builder(this)
            .setTitle("Iniciar sesión en YouTube")
            .setMessage(
                "Se abrirá YouTube en tu navegador.\n\n" +
                "1. Inicia sesión con tu cuenta de Google\n" +
                "2. Cuando termines, vuelve a EricCatch\n" +
                "3. Toca \"Ya inicié sesión\"\n\n" +
                "Esto permite descargar videos en HD sin bloqueos."
            )
            .setPositiveButton("Abrir YouTube") { _, _ ->
                openYouTubeInChrome()
            }
            .setNegativeButton("Cancelar") { _, _ -> finish() }
            .setCancelable(false)
            .show()
    }

    private fun openYouTubeInChrome() {
        // Primero sincronizar cookies entre Chrome y WebView
        CookieManager.getInstance().apply {
            setAcceptCookie(true)
            flush()
        }

        try {
            // Custom Chrome Tab — usa Chrome real, Google no lo bloquea
            val customTabsIntent = CustomTabsIntent.Builder()
                .setShowTitle(true)
                .build()
            customTabsIntent.launchUrl(
                this,
                Uri.parse("https://accounts.google.com/signin/v2/identifier?service=youtube&hl=es&continue=https://www.youtube.com")
            )
        } catch (e: Exception) {
            // Fallback: abrir en cualquier navegador disponible
            val intent = Intent(Intent.ACTION_VIEW,
                Uri.parse("https://www.youtube.com/signin"))
            startActivity(intent)
        }

        // Mostrar botón para cuando el usuario regrese
        showReturnDialog()
    }

    private fun showReturnDialog() {
        AlertDialog.Builder(this)
            .setTitle("¿Terminaste de iniciar sesión?")
            .setMessage("Toca \"Ya inicié sesión\" cuando hayas completado el login en el navegador.")
            .setPositiveButton("Ya inicié sesión") { _, _ ->
                extractCookiesFromSystem()
            }
            .setNegativeButton("Volver a intentar") { _, _ ->
                openYouTubeInChrome()
            }
            .setNeutralButton("Cancelar") { _, _ -> finish() }
            .setCancelable(false)
            .show()
    }

    private fun extractCookiesFromSystem() {
        val cookieManager = CookieManager.getInstance()
        cookieManager.flush()

        val sb = StringBuilder()
        sb.appendLine("# Netscape HTTP Cookie File")
        sb.appendLine("# Generated by EricCatch")
        sb.appendLine()

        val expiry = (System.currentTimeMillis() / 1000L) + (365 * 24 * 3600L)
        val seenCookies = mutableSetOf<String>()

        val urlsToHosts = mapOf(
            "https://www.youtube.com"      to ".youtube.com",
            "https://youtube.com"          to ".youtube.com",
            "https://m.youtube.com"        to ".youtube.com",
            "https://accounts.google.com"  to ".google.com",
            "https://www.google.com"       to ".google.com"
        )

        for ((url, host) in urlsToHosts) {
            val cookieStr = cookieManager.getCookie(url) ?: continue
            cookieStr.split(";").forEach { part ->
                val trimmed = part.trim()
                if (trimmed.isBlank() || !trimmed.contains("=")) return@forEach
                val eqIdx = trimmed.indexOf("=")
                val name  = trimmed.substring(0, eqIdx).trim()
                val value = trimmed.substring(eqIdx + 1).trim()
                if (name.isBlank()) return@forEach
                val key = "$host:$name"
                if (!seenCookies.add(key)) return@forEach
                sb.appendLine("$host\tTRUE\t/\tTRUE\t$expiry\t$name\t$value")
            }
        }

        val content = sb.toString()
        val lines = content.lines().filter { it.isNotBlank() && !it.startsWith("#") }

        Log.d(TAG, "Cookie lines: ${lines.size}")
        Log.d(TAG, "Has SID=${content.contains("\tSID\t")}, " +
                "SAPISID=${content.contains("SAPISID")}, " +
                "LOGIN_INFO=${content.contains("LOGIN_INFO")}")

        if (lines.size < 3) {
            // No se encontraron cookies — posiblemente Chrome no comparte con WebView en este dispositivo
            AlertDialog.Builder(this)
                .setTitle("No se detectó sesión")
                .setMessage(
                    "No se encontraron cookies de YouTube.\n\n" +
                    "Esto puede pasar porque Chrome y la app no comparten cookies en tu dispositivo.\n\n" +
                    "Alternativa: Abre YouTube en el navegador interno de la app (más compatible)."
                )
                .setPositiveButton("Usar navegador interno") { _, _ ->
                    startActivity(Intent(this, WebViewLoginActivity::class.java))
                    finish()
                }
                .setNegativeButton("Cancelar") { _, _ -> finish() }
                .show()
            return
        }

        File(filesDir, COOKIES_FILE).writeText(content)
        Log.d(TAG, "Saved ${lines.size} cookie lines")

        Toast.makeText(this, "✓ Sesión guardada. ¡Ya puedes descargar en HD!", Toast.LENGTH_LONG).show()
        setResult(RESULT_OK)
        finish()
    }
}
