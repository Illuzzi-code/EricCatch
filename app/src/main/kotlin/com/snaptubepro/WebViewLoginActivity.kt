package com.ericcatch

import android.annotation.SuppressLint
import android.os.Bundle
import android.util.Log
import android.view.View
import android.webkit.CookieManager
import android.webkit.WebChromeClient
import android.webkit.WebResourceRequest
import android.webkit.WebView
import android.webkit.WebViewClient
import android.widget.Toast
import androidx.appcompat.app.AppCompatActivity
import androidx.appcompat.widget.Toolbar
import android.widget.ProgressBar
import java.io.File

/**
 * Alternativa al login por Chrome — usa WebView interno.
 * Google puede mostrar aviso de seguridad, pero funciona.
 * Se activa automáticamente si Chrome no comparte cookies.
 */
class WebViewLoginActivity : AppCompatActivity() {

    private lateinit var webView: WebView
    private lateinit var progressBar: ProgressBar
    private var cookiesSaved = false

    companion object {
        private const val TAG = "WebViewLogin"
    }

    @SuppressLint("SetJavaScriptEnabled")
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_webview_login)

        val toolbar = findViewById<Toolbar>(R.id.webviewToolbar)
        setSupportActionBar(toolbar)
        supportActionBar?.setDisplayHomeAsUpEnabled(true)

        webView = findViewById(R.id.loginWebView)
        progressBar = findViewById(R.id.webviewProgress)

        val cookieManager = CookieManager.getInstance()
        cookieManager.setAcceptCookie(true)
        cookieManager.setAcceptThirdPartyCookies(webView, true)

        webView.settings.apply {
            javaScriptEnabled = true
            domStorageEnabled = true
            // UA de Chrome desktop para evitar redirects móviles
            userAgentString = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) " +
                    "AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
        }

        webView.webChromeClient = object : WebChromeClient() {
            override fun onProgressChanged(view: WebView, newProgress: Int) {
                progressBar.progress = newProgress
                progressBar.visibility = if (newProgress < 100) View.VISIBLE else View.GONE
            }
        }

        webView.webViewClient = object : WebViewClient() {
            override fun onPageFinished(view: WebView, url: String) {
                super.onPageFinished(view, url)
                Log.d(TAG, "Page: $url")

                // Detectar llegada a YouTube autenticado
                if ((url.startsWith("https://www.youtube.com") || url.startsWith("https://youtube.com")) &&
                    !url.contains("accounts.google") &&
                    !url.contains("signin") &&
                    !url.contains("ServiceLogin") &&
                    !url.contains("challenge") &&
                    !cookiesSaved
                ) {
                    view.postDelayed({ saveCookies() }, 3000)
                }
            }

            override fun shouldOverrideUrlLoading(view: WebView, request: WebResourceRequest) = false
        }

        webView.loadUrl("https://accounts.google.com/signin/v2/identifier?service=youtube&hl=es&continue=https://www.youtube.com")
    }

    override fun onSupportNavigateUp(): Boolean {
        finish()
        return true
    }

    private fun saveCookies() {
        if (cookiesSaved) return
        cookiesSaved = true

        val cookieManager = CookieManager.getInstance()
        cookieManager.flush()

        val sb = StringBuilder()
        sb.appendLine("# Netscape HTTP Cookie File")
        sb.appendLine("# Generated by EricCatch")
        sb.appendLine()

        val expiry = (System.currentTimeMillis() / 1000L) + (365 * 24 * 3600L)
        val seenCookies = mutableSetOf<String>()

        val urlsToHosts = mapOf(
            "https://www.youtube.com"     to ".youtube.com",
            "https://youtube.com"         to ".youtube.com",
            "https://accounts.google.com" to ".google.com",
            "https://www.google.com"      to ".google.com"
        )

        for ((url, host) in urlsToHosts) {
            val cookieStr = cookieManager.getCookie(url) ?: continue
            cookieStr.split(";").forEach { part ->
                val trimmed = part.trim()
                if (trimmed.isBlank() || !trimmed.contains("=")) return@forEach
                val eqIdx = trimmed.indexOf("=")
                val name = trimmed.substring(0, eqIdx).trim()
                val value = trimmed.substring(eqIdx + 1).trim()
                if (name.isBlank()) return@forEach
                if (!seenCookies.add("$host:$name")) return@forEach
                sb.appendLine("$host\tTRUE\t/\tTRUE\t$expiry\t$name\t$value")
            }
        }

        val content = sb.toString()
        val lines = content.lines().filter { it.isNotBlank() && !it.startsWith("#") }

        Log.d(TAG, "Cookie lines: ${lines.size}, has SID: ${content.contains("\tSID\t")}")

        if (lines.size < 3) {
            Toast.makeText(this, "Sesión no detectada aún. Espera a que cargue YouTube.", Toast.LENGTH_LONG).show()
            cookiesSaved = false
            return
        }

        File(filesDir, LoginActivity.COOKIES_FILE).writeText(content)
        Toast.makeText(this, "✓ Sesión guardada. ¡Ya puedes descargar en HD!", Toast.LENGTH_LONG).show()
        setResult(RESULT_OK)
        finish()
    }
}
